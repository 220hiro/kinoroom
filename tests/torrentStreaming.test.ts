import test from 'node:test';
import assert from 'node:assert/strict';
import { once } from 'node:events';
import { getOrAddTorrent } from '../src/lib/services/torrents';

test('metadata lookup starts torrents deselected (controlled client, no public swarm)', async () => {
  const previous = globalThis._webtorrentClient;
  let options: any;
  const torrent = { ready: true, files: [{}], numPeers: 1 };
  globalThis._webtorrentClient = {
    get: async () => null,
    add: (_id: string, opts: any) => { options = opts; return torrent; }
  };
  try {
    assert.equal(await getOrAddTorrent('controlled-fixture'), torrent);
    assert.equal(options.deselect, true);
  } finally {
    globalThis._webtorrentClient = previous;
  }
});

test('real WebTorrent on loopback reads requested bytes after cancelling another viewer, without whole-file selection', { timeout: 20_000 }, async () => {
  const { default: WebTorrent } = await import('webtorrent');
  const { default: MemoryStore } = await import('memory-chunk-store');
  const opts = { tracker: false, dht: false, lsd: false, utp: false, webSeeds: false, natUpnp: false, natPmp: false };
  const sender = new WebTorrent(opts);
  const receiver = new WebTorrent(opts);
  const fixture = Buffer.alloc(8 * 1024 * 1024, 37); // Our own generated bytes; no media source.
  const clientErrors: Error[] = [];
  sender.on('error', error => clientErrors.push(error));
  receiver.on('error', error => clientErrors.push(error));
  try {
    const seeded: any = await new Promise((resolve, reject) => {
      const torrent = sender.seed(fixture, { name: 'owned-fixture.bin', pieceLength: 64 * 1024, announce: [], private: true, store: MemoryStore }, resolve);
      torrent.once('error', reject);
    });
    const receiving: any = receiver.add(seeded.torrentFile, { deselect: true, store: MemoryStore });
    await once(receiving, 'ready');
    const connected = once(receiving, 'wire');
    receiving.addPeer(`127.0.0.1:${sender.torrentPort}`);
    await connected;
    // Allow the bitfield handshake; the seed is available, but no playback range is selected.
    await new Promise(resolve => setTimeout(resolve, 100));
    assert.equal(receiving.downloaded, 0);

    const firstViewer = receiving.files[0].createReadStream({ start: 0, end: 1024 * 1024 - 1 });
    const start = 4 * 1024 * 1024;
    const end = start + 128 * 1024 - 1;
    const secondViewer = receiving.files[0].createReadStream({ start, end });
    const closed = once(firstViewer, 'close');
    firstViewer.destroy();
    await closed;
    const chunks: Buffer[] = [];
    for await (const chunk of secondViewer) chunks.push(Buffer.from(chunk));
    assert.deepEqual(Buffer.concat(chunks), fixture.subarray(start, end + 1));
    assert.ok(receiving.downloaded < fixture.length, 'Unrequested remainder must not become a full-file download');
    const afterRead = receiving.downloaded;
    await new Promise(resolve => setTimeout(resolve, 100));
    assert.equal(receiving.downloaded, afterRead, 'After range readers close, payload downloads must stop');
    assert.equal(clientErrors.length, 0, 'Loopback clients must not report errors');
  } finally {
    await Promise.all([sender, receiver].map(client => new Promise<void>(resolve => client.destroy(() => resolve()))));
  }
});
